def build():
    src = json.load(io.open(SRC, encoding="utf-8"))
    try:
        corpus = set(json.load(io.open(CORPUS, encoding="utf-8")))
    except Exception:
        corpus = set()
    result = {}
    for lang, table in (("ja_JP", JA), ("ko_KR", KO)):
        out = {k: v for k, v in table.items() if k in src or k in corpus}
        path = os.path.join(ROOT, "locale", lang, "strings.json")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        io.open(path, "w", encoding="utf-8", newline="\n").write(
            json.dumps(out, ensure_ascii=False, indent=2, sort_keys=True)
        )
        result[lang] = len(out)
    return result


def main():
    r = build()
    print("[ja_ko] " + ", ".join("%s=%d" % (k, v) for k, v in r.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
